    faq_items = "".join(
        f'<details class="faq-item"><summary><span>{esc(f["q"][lang])}</span><span class="faq-plus" aria-hidden="true"></span></summary><p class="faq-a">{esc(f["a"][lang])}</p></details>'
        for f in faqs
    )
