# --------------------------------------------------------------------------- parsing
class Tag:
    __slots__ = ("name", "attrs", "raw", "start", "end")

    def __init__(self, name, attrs, raw, start):
        self.name, self.attrs, self.raw, self.start = name, attrs, raw, start
        self.end = start + len(raw)


class PageParser(HTMLParser):
    """Collects every start tag (with its source offsets) plus services and FAQs."""

    def __init__(self, source: str):
        super().__init__(convert_charrefs=True)
        self.source = source
        self.line_starts = [0]
        for match in re.finditer("\n", source):
            self.line_starts.append(match.end())
        self.tags: list[Tag] = []
        self.services: list[dict] = []
        self.faqs: list[dict] = []
        self._section = ""
        self._group = None
        self._in_faq = False
        self.feed(source)

    def _offset(self) -> int:
        line, col = self.getpos()
        return self.line_starts[line - 1] + col

    def handle_startendtag(self, name, attrs):
        self.handle_starttag(name, attrs)

    def handle_starttag(self, name, attrs):
        attrs = {key: (value if value is not None else "") for key, value in attrs}
        tag = Tag(name, attrs, self.get_starttag_text(), self._offset())
        self.tags.append(tag)
        classes = attrs.get("class", "").split()
        both = "data-en" in attrs and "data-ar" in attrs
        text = {"en": attrs.get("data-en", ""), "ar": attrs.get("data-ar", "")}

        if name == "section" and attrs.get("id"):
            self._section = attrs["id"]
            self._group = None
        if "agency-h" in classes and both:
            self._group = text
        if "data-service" in attrs:
            self.services.append({"section": self._section, "group": self._group, "title": None, "desc": None, "price": None})
        elif self.services and both:
            current = self.services[-1]
            if "data-request-title" in attrs and current["title"] is None:
                current["title"] = text
            elif "ai-desc" in classes and current["desc"] is None and current["price"] is None:
                current["desc"] = text
            elif "data-request-price" in attrs and current["price"] is None:
                current["price"] = text

        if name == "details" and "faq-item" in classes:
            self._in_faq = True
            self.faqs.append({"q": None, "a": None})
        elif self._in_faq and both:
            current = self.faqs[-1]
            if "faq-a" in classes:
                current["a"] = text
            elif current["q"] is None:
                current["q"] = text

    def handle_endtag(self, name):
        if name == "details":
            self._in_faq = False


def parse_price(label: str):
    """'AED 1,999 / day' -> (1999, 'DAY'); 'AED 499' -> (499, None)."""
    match = re.search(r"([\d,]+)\s*(?:/\s*(\w+))?", label)
    if not match:
        return None, None
    unit = {"day": "DAY", "mo": "MON", "month": "MON"}.get((match.group(2) or "").lower())
    return int(match.group(1).replace(",", "")), unit


