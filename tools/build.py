def replace_head(source: str, block: str) -> str:
    start = source.index(HEAD_START)
    end = source.index(HEAD_END) + len(HEAD_END)
    return source[:start] + block + source[end:]


# --------------------------------------------------------------------------- Arabic page
RELATIVE_SKIP = ("http:", "https:", "//", "/", "#", "data:", "mailto:", "tel:", "javascript:")


def set_attr(raw: str, name: str, value: str) -> str:
    pattern = re.compile(r'(?<![-\w:])' + re.escape(name) + r'="[^"]*"')
    replacement = f'{name}="{attr(value)}"'
    if pattern.search(raw):
        return pattern.sub(lambda _: replacement, raw, count=1)
    closing = "/>" if raw.endswith("/>") else ">"
    return f"{raw[: -len(closing)].rstrip()} {replacement}{closing}"


def to_arabic_url(url: str) -> str:
    """Rewrites a URL that is relative to / so it works from /ar/."""
    if not url or url.startswith(RELATIVE_SKIP):
        return url
    if url == "./":
        return "../"
    if url == "ar/":
        return "./"
    return "../" + url


def build_arabic(source: str, page_for_head: PageParser) -> str:
    # Work on the page with an empty head block, then drop the Arabic head in.
    body = replace_head(source, HEAD_START_LINE + "\n" + HEAD_END)
    page = PageParser(body)
    edits = []  # (start, end, replacement), applied back to front
    for tag in page.tags:
        raw, attrs = tag.raw, tag.attrs
        if "data-ph-ar" in attrs:
            raw = set_attr(raw, "placeholder", attrs["data-ph-ar"])
        if "data-aria-ar" in attrs:
            raw = set_attr(raw, "aria-label", attrs["data-aria-ar"])
        for name in ("href", "src"):
            if name in attrs and to_arabic_url(attrs[name]) != attrs[name]:
                raw = set_attr(raw, name, to_arabic_url(attrs[name]))
        if "lang-btn" in attrs.get("class", "").split():
            is_arabic_link = attrs.get("data-lang") == "ar"
            raw = raw.replace(' aria-current="true"', "")
            raw = set_attr(raw, "class", "lang-btn active" if is_arabic_link else "lang-btn")
            if is_arabic_link:
                raw = set_attr(raw, "aria-current", "true")
        if raw != tag.raw:
            edits.append((tag.start, tag.end, raw))
        if "data-en" in attrs and "data-ar" in attrs:
            # These elements hold plain text only (the script swaps textContent the same way).
            text_end = body.index("<", tag.end)
            edits.append((tag.end, text_end, html.escape(attrs["data-ar"], quote=False)))

    out = body
    for start, end, replacement in sorted(edits, reverse=True):
        out = out[:start] + replacement + out[end:]

    marker = '<html lang="en" dir="ltr">'
    assert out.count(marker) == 1, "expected exactly one <html lang> tag"
    out = out.replace(marker, '<html lang="ar" dir="rtl">')
    return replace_head(out, head_block("ar", page_for_head))


